"""Builds configs/all_rails/prompts.yml from the jailbreak_self_check and content_safety prompts, so the
"all rails" profile always uses exactly the same judge prompts as the individual profiles.

Run after editing either source:  python3 nemo-guardrails/build_all_rails.py
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent / "configs"
SOURCES = ["jailbreak_self_check", "content_safety"]

parts = []
for name in SOURCES:
    text = (HERE / name / "prompts.yml").read_text(encoding="utf-8")
    head, sep, body = text.partition("prompts:\n")
    if not sep:
        raise SystemExit(f"{name}/prompts.yml: expected a top-level 'prompts:' list")
    parts.append(f"  # ---- from {name}/prompts.yml ----\n" + body.rstrip() + "\n")

out = ("# GENERATED by build_all_rails.py from " + " + ".join(SOURCES) + ". Do not edit by hand.\n"
       "prompts:\n" + "\n".join(parts))
(HERE / "all_rails" / "prompts.yml").write_text(out, encoding="utf-8")
print(f"wrote configs/all_rails/prompts.yml ({len(out.splitlines())} lines)")
