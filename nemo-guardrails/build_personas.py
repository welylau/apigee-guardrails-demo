#!/usr/bin/env python3
"""Generate NeMo topic-control persona configs and the UI persona list from personas.json.

Writes:
  nemo-guardrails/configs/<persona id>/config.yml   (judge model wiring, same for every persona)
  nemo-guardrails/configs/<persona id>/prompts.yml  (that persona's allowed / forbidden topics)
  demo-ui/static/nemo-personas.js                   (window.NEMO_PERSONAS for the UI)

Usage:
  python3 nemo-guardrails/build_personas.py           # regenerate
  python3 nemo-guardrails/build_personas.py --check   # fail if anything is stale or not allow-listed
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
SOURCE = HERE / "personas.json"
UI_FILE = ROOT / "demo-ui" / "static" / "nemo-personas.js"
# Allow-lists that must contain every persona id (the request is rejected / downgraded otherwise).
ALLOW_LISTS = {
    ROOT / "demo-ui" / "app.py": re.compile(r"NEMO_PROFILES\s*=\s*\((.*?)\)", re.S),
    ROOT / "guardrail-proxy" / "apiproxy" / "resources" / "jsc" / "nemo-input.js": re.compile(r"ALLOWED_PROFILES\s*=\s*\{(.*?)\}", re.S),
}

CONFIG_YML = """models:
  - type: main
    engine: openai
    model: gemini-2.5-flash-lite
    parameters:
      base_url: "http://127.0.0.1:8081/v1"
      api_key: "vertex-adc"

  - type: topic_control
    engine: openai
    model: gemini-2.5-flash-lite
    parameters:
      base_url: "http://127.0.0.1:8081/v1"
      api_key: "vertex-adc"

rails:
  input:
    flows:
      - topic safety check input $model=topic_control
"""


def prompts_yml(p):
    lines = [
        "prompts:",
        "  - task: topic_safety_check_input $model=topic_control",
        "    content: |",
        f"      You are {p['role']}. Your role is to ensure that you respond only to relevant queries "
        "and adhere strictly to the following topic boundaries.",
        "",
        "      Allowed topics (on-topic):",
        *[f"      - {a}" for a in p["allowed"]],
        "",
        "      Forbidden topics (off-topic - VIOLATIONS):",
        *[f"      - {f}" for f in p["forbidden"]],
    ]
    return "\n".join(lines) + "\n"


def ui_js(personas):
    public = [
        {k: p[k] for k in ("id", "label", "icon", "allowed_short", "forbidden_short")}
        for p in personas
    ]
    body = json.dumps(public, ensure_ascii=False, indent=2)
    return (
        "// Generated by nemo-guardrails/build_personas.py from nemo-guardrails/personas.json. Do not edit by hand.\n"
        f"window.NEMO_PERSONAS = {body};\n"
    )


def outputs():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    personas = data["personas"]
    ids = [p["id"] for p in personas]
    assert len(ids) == len(set(ids)), "duplicate persona id"
    for pid in ids:
        assert re.fullmatch(r"topic_[a-z]+", pid) or pid == "topic_control", f"bad persona id: {pid}"
    files = {}
    for p in personas:
        d = HERE / "configs" / p["id"]
        files[d / "config.yml"] = CONFIG_YML
        files[d / "prompts.yml"] = prompts_yml(p)
    files[UI_FILE] = ui_js(personas)
    return ids, files


def main():
    check = "--check" in sys.argv[1:]
    ids, files = outputs()
    problems = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            problems.append(f"stale: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    for path, pattern in ALLOW_LISTS.items():
        m = pattern.search(path.read_text(encoding="utf-8"))
        listed = set(re.findall(r"[a-z_]+", m.group(1))) if m else set()
        missing = [i for i in ids if i not in listed]
        if missing:
            problems.append(f"{path.relative_to(ROOT)} allow-list is missing: {', '.join(missing)}")
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    print(f"OK: {len(ids)} personas ({', '.join(ids)})")


if __name__ == "__main__":
    main()
